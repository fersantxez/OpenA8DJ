#ifndef OPENA8DJ_CTL_BASE
#define OPENA8DJ_CTL_BASE 0x800
#endif

#define OPENA8DJ_DRIVER_API_VERSION 2

#define OPENA8DJ_VENDOR_ID 0x17CC
#define OPENA8DJ_PRODUCT_ID 0x1978

#define OPENA8DJ_INPUT_CHANNELS 8
#define OPENA8DJ_OUTPUT_CHANNELS 8
#define OPENA8DJ_STEREO_PAIRS 4
#define OPENA8DJ_SAMPLE_RATE_COUNT 4
#define OPENA8DJ_STABLE_SAMPLE_RATE_COUNT 2
#define OPENA8DJ_CHANNEL_NAME_LENGTH 32
#define OPENA8DJ_SURFACE_NAME_LENGTH 64
#define OPENA8DJ_ENDPOINT_NAME_LENGTH 64
#define OPENA8DJ_TOTAL_CHANNELS (OPENA8DJ_INPUT_CHANNELS + OPENA8DJ_OUTPUT_CHANNELS)

#define OPENA8DJ_DEFAULT_SAMPLE_RATE 48000
#define OPENA8DJ_DEFAULT_BUFFER_FRAMES 512
#define OPENA8DJ_MIN_BUFFER_FRAMES 15
#define OPENA8DJ_MAX_BUFFER_FRAMES 4096

#define OPENA8DJ_PROFILE_TIMECODE_VINYL 0
#define OPENA8DJ_PROFILE_TIMECODE_CD_LINE 1
#define OPENA8DJ_PROFILE_PHONO 2
#define OPENA8DJ_PROFILE_UNLOCK 3

#define OPENA8DJ_COMPONENT_ABSENT 0
#define OPENA8DJ_COMPONENT_PLANNED 1
#define OPENA8DJ_COMPONENT_STUB 2
#define OPENA8DJ_COMPONENT_READY 3

#define OPENA8DJ_ENDPOINT_MODEL_NONE 0
#define OPENA8DJ_ENDPOINT_MODEL_SINGLE_8CH 1
#define OPENA8DJ_ENDPOINT_MODEL_FOUR_STEREO_PAIRS 2
#define OPENA8DJ_ENDPOINT_MODEL_DUAL_PROTOTYPE 3

#define OPENA8DJ_CHANNEL_DIRECTION_RENDER 0
#define OPENA8DJ_CHANNEL_DIRECTION_CAPTURE 1

#define OPENA8DJ_RATE_FLAG_44100 0x00000001u
#define OPENA8DJ_RATE_FLAG_48000 0x00000002u
#define OPENA8DJ_RATE_FLAG_88200 0x00000004u
#define OPENA8DJ_RATE_FLAG_96000 0x00000008u

#define OPENA8DJ_SURFACE_FLAG_USB_TRANSPORT 0x00000001u
#define OPENA8DJ_SURFACE_FLAG_CONTROLS 0x00000002u
#define OPENA8DJ_SURFACE_FLAG_AUDIO_ENDPOINTS 0x00000004u
#define OPENA8DJ_SURFACE_FLAG_ISOCHRONOUS_ENGINE 0x00000008u
#define OPENA8DJ_SURFACE_FLAG_MIDI 0x00000010u
#define OPENA8DJ_SURFACE_FLAG_ASIO 0x00000020u
#define OPENA8DJ_SURFACE_FLAG_EXPERIMENTAL 0x80000000u

DEFINE_GUID(GUID_DEVINTERFACE_OPENA8DJ_USB,
    0xa3ca3315, 0x46ee, 0x416b, 0xbe, 0x25, 0xfb, 0x52, 0xf3, 0xd8, 0x44, 0x22);

#define IOCTL_OPENA8DJ_GET_USB_INFO \
    CTL_CODE(FILE_DEVICE_UNKNOWN, OPENA8DJ_CTL_BASE + 0, METHOD_BUFFERED, FILE_READ_DATA)
#define IOCTL_OPENA8DJ_GET_CAPABILITIES \
    CTL_CODE(FILE_DEVICE_UNKNOWN, OPENA8DJ_CTL_BASE + 1, METHOD_BUFFERED, FILE_READ_DATA)
#define IOCTL_OPENA8DJ_GET_CONTROL_STATE \
    CTL_CODE(FILE_DEVICE_UNKNOWN, OPENA8DJ_CTL_BASE + 2, METHOD_BUFFERED, FILE_READ_DATA)
#define IOCTL_OPENA8DJ_SET_CONTROL_STATE \
    CTL_CODE(FILE_DEVICE_UNKNOWN, OPENA8DJ_CTL_BASE + 3, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)
#define IOCTL_OPENA8DJ_APPLY_PROFILE \
    CTL_CODE(FILE_DEVICE_UNKNOWN, OPENA8DJ_CTL_BASE + 4, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)
#define IOCTL_OPENA8DJ_GET_AUDIO_FORMAT \
    CTL_CODE(FILE_DEVICE_UNKNOWN, OPENA8DJ_CTL_BASE + 5, METHOD_BUFFERED, FILE_READ_DATA)
#define IOCTL_OPENA8DJ_SET_AUDIO_FORMAT \
    CTL_CODE(FILE_DEVICE_UNKNOWN, OPENA8DJ_CTL_BASE + 6, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)
#define IOCTL_OPENA8DJ_START_STREAMING \
    CTL_CODE(FILE_DEVICE_UNKNOWN, OPENA8DJ_CTL_BASE + 7, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)
#define IOCTL_OPENA8DJ_STOP_STREAMING \
    CTL_CODE(FILE_DEVICE_UNKNOWN, OPENA8DJ_CTL_BASE + 8, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)
#define IOCTL_OPENA8DJ_GET_STREAM_STATE \
    CTL_CODE(FILE_DEVICE_UNKNOWN, OPENA8DJ_CTL_BASE + 9, METHOD_BUFFERED, FILE_READ_DATA)
#define IOCTL_OPENA8DJ_GET_SURFACE \
    CTL_CODE(FILE_DEVICE_UNKNOWN, OPENA8DJ_CTL_BASE + 10, METHOD_BUFFERED, FILE_READ_DATA)
#define IOCTL_OPENA8DJ_GET_TOPOLOGY \
    CTL_CODE(FILE_DEVICE_UNKNOWN, OPENA8DJ_CTL_BASE + 11, METHOD_BUFFERED, FILE_READ_DATA)
#define IOCTL_OPENA8DJ_GET_DIAGNOSTICS \
    CTL_CODE(FILE_DEVICE_UNKNOWN, OPENA8DJ_CTL_BASE + 12, METHOD_BUFFERED, FILE_READ_DATA)

typedef struct _OPENA8DJ_USB_INFO {
    ULONG Size;
    USHORT VendorId;
    USHORT ProductId;
    UCHAR ConfiguredInterfaceCount;
    BOOLEAN HasBulkOut;
    BOOLEAN HasBulkIn;
    BOOLEAN HasIsoIn;
    BOOLEAN HasIsoOut;
} OPENA8DJ_USB_INFO, *POPENA8DJ_USB_INFO;

typedef struct _OPENA8DJ_CAPABILITIES {
    ULONG Size;
    ULONG ApiVersion;
    USHORT VendorId;
    USHORT ProductId;
    UCHAR InputChannels;
    UCHAR OutputChannels;
    UCHAR StereoPairs;
    UCHAR MidiInputs;
    UCHAR MidiOutputs;
    ULONG SampleRates[OPENA8DJ_SAMPLE_RATE_COUNT];
    ULONG MinBufferFrames;
    ULONG MaxBufferFrames;
    ULONG DefaultBufferFrames;
    CHAR InputPairNames[OPENA8DJ_STEREO_PAIRS][OPENA8DJ_CHANNEL_NAME_LENGTH];
    CHAR OutputPairNames[OPENA8DJ_STEREO_PAIRS][OPENA8DJ_CHANNEL_NAME_LENGTH];
    BOOLEAN Experimental;
    BOOLEAN WindowsAudioEndpointExposed;
    BOOLEAN UsbTransportReady;
    BOOLEAN MidiReady;
    BOOLEAN ControlsReady;
} OPENA8DJ_CAPABILITIES, *POPENA8DJ_CAPABILITIES;

typedef struct _OPENA8DJ_WINDOWS_SURFACE {
    ULONG Size;
    ULONG ApiVersion;
    ULONG SurfaceFlags;
    ULONG StableSampleRateFlags;
    ULONG PlannedSampleRateFlags;
    ULONG AudioEndpointState;
    ULONG UsbTransportState;
    ULONG IsochronousEngineState;
    ULONG MidiState;
    ULONG ControlState;
    ULONG AsioState;
    ULONG EndpointModel;
    CHAR DriverModel[OPENA8DJ_SURFACE_NAME_LENGTH];
    CHAR AudioModel[OPENA8DJ_SURFACE_NAME_LENGTH];
    CHAR StreamingModel[OPENA8DJ_SURFACE_NAME_LENGTH];
    CHAR SafetyPolicy[OPENA8DJ_SURFACE_NAME_LENGTH];
} OPENA8DJ_WINDOWS_SURFACE, *POPENA8DJ_WINDOWS_SURFACE;

typedef struct _OPENA8DJ_CHANNEL_DESCRIPTOR {
    ULONG Size;
    ULONG Direction;
    ULONG ChannelIndex;
    ULONG PairIndex;
    ULONG PairChannelIndex;
    CHAR Name[OPENA8DJ_CHANNEL_NAME_LENGTH];
} OPENA8DJ_CHANNEL_DESCRIPTOR, *POPENA8DJ_CHANNEL_DESCRIPTOR;

typedef struct _OPENA8DJ_TOPOLOGY {
    ULONG Size;
    ULONG ApiVersion;
    ULONG EndpointModel;
    ULONG RenderEndpointCount;
    ULONG CaptureEndpointCount;
    ULONG RenderChannelCount;
    ULONG CaptureChannelCount;
    CHAR RenderEndpointName[OPENA8DJ_ENDPOINT_NAME_LENGTH];
    CHAR CaptureEndpointName[OPENA8DJ_ENDPOINT_NAME_LENGTH];
    OPENA8DJ_CHANNEL_DESCRIPTOR Channels[OPENA8DJ_TOTAL_CHANNELS];
} OPENA8DJ_TOPOLOGY, *POPENA8DJ_TOPOLOGY;

typedef struct _OPENA8DJ_CONTROL_STATE {
    ULONG Size;
    UCHAR InputMode;
    UCHAR GndLiftTCVinyl;
    UCHAR GndLiftTCCDLine;
    UCHAR GndLiftPhono;
    UCHAR SoftwareLock;
} OPENA8DJ_CONTROL_STATE, *POPENA8DJ_CONTROL_STATE;

typedef struct _OPENA8DJ_PROFILE_REQUEST {
    ULONG Size;
    ULONG Profile;
} OPENA8DJ_PROFILE_REQUEST, *POPENA8DJ_PROFILE_REQUEST;

typedef struct _OPENA8DJ_AUDIO_FORMAT {
    ULONG Size;
    ULONG SampleRate;
    ULONG InputChannels;
    ULONG OutputChannels;
    ULONG BufferFrames;
} OPENA8DJ_AUDIO_FORMAT, *POPENA8DJ_AUDIO_FORMAT;

typedef struct _OPENA8DJ_STREAM_STATE {
    ULONG Size;
    BOOLEAN Streaming;
    BOOLEAN StreamingEngineReady;
    ULONG SampleRate;
    ULONG BufferFrames;
    ULONG64 RenderFramesSubmitted;
    ULONG64 CaptureFramesDelivered;
    ULONG64 UsbUnderruns;
    ULONG64 UsbOverruns;
    ULONG64 UsbInPacketsCompleted;
    ULONG64 UsbOutPacketsCompleted;
    ULONG64 UsbPacketErrors;
    ULONG64 LateCompletions;
} OPENA8DJ_STREAM_STATE, *POPENA8DJ_STREAM_STATE;

typedef struct _OPENA8DJ_DIAGNOSTICS {
    ULONG Size;
    ULONG ApiVersion;
    ULONG64 StartRequests;
    ULONG64 RejectedStartRequests;
    ULONG64 StopRequests;
    ULONG64 FormatChanges;
    ULONG64 ControlWrites;
    ULONG64 ProfileApplies;
    OPENA8DJ_STREAM_STATE StreamState;
} OPENA8DJ_DIAGNOSTICS, *POPENA8DJ_DIAGNOSTICS;

